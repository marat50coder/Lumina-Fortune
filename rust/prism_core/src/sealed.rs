// ─────────────────────────────────────────────────────────────
// sealed — raw byte arrays, bit-for-bit copies of the Dart
// `lib/prism/sealed_bytes.dart` module. Every array below is
// meaningful only after `cloak::unseal` runs on it.
//
// Static scanners (`strings libprism_core.so`) see random noise
// here. Each array is additionally scrambled on the wire by
// `obfstr::obfbytes!` so even a `.rodata` dump never contains
// the sealed payload as a contiguous run.
// ─────────────────────────────────────────────────────────────

use obfstr::obfbytes;

// Index enum — the FFI entry point takes an opaque `u32` so the
// exported symbol names do not leak the semantic purpose of
// each sealed value. Keep in sync with
// `lib/prism/native/prism_ffi.dart::_SealedIndex`.
#[repr(u32)]
#[derive(Copy, Clone, Debug)]
pub enum Idx {
    Endpoint = 0,
    GcdBase = 1,
    AttributionKey = 2,
    MessagingProject = 3,
    RelaySecret = 4,

    UaProduct = 10,
    UaLinuxOpen = 11,
    UaBuildLabel = 12,
    UaBuildClose = 13,
    UaEngineLabel = 14,
    UaEngineTail = 15,
    UaChromeLabel = 16,
    UaMobileSafari = 17,
    ChromeVersion = 18,
    WebkitVersion = 19,
    UaAppIdToken = 20,
    UaAppNameToken = 21,
    AppNameToken = 22,

    JsSafeArea = 30,
    JsKeyboard = 31,
    JsAutoplay = 32,
    JsHop = 33,
}

impl Idx {
    pub fn from_raw(raw: u32) -> Option<Self> {
        Some(match raw {
            0 => Idx::Endpoint,
            1 => Idx::GcdBase,
            2 => Idx::AttributionKey,
            3 => Idx::MessagingProject,
            4 => Idx::RelaySecret,
            10 => Idx::UaProduct,
            11 => Idx::UaLinuxOpen,
            12 => Idx::UaBuildLabel,
            13 => Idx::UaBuildClose,
            14 => Idx::UaEngineLabel,
            15 => Idx::UaEngineTail,
            16 => Idx::UaChromeLabel,
            17 => Idx::UaMobileSafari,
            18 => Idx::ChromeVersion,
            19 => Idx::WebkitVersion,
            20 => Idx::UaAppIdToken,
            21 => Idx::UaAppNameToken,
            22 => Idx::AppNameToken,
            30 => Idx::JsSafeArea,
            31 => Idx::JsKeyboard,
            32 => Idx::JsAutoplay,
            33 => Idx::JsHop,
            _ => return None,
        })
    }
}

