// `unsealUrlPrivacy` / `unsealUrlSupport` intentionally removed
// — the Rust-guard template keeps those public legal pages on
// the Play Console listing only, so no client-side opener is
// needed and no partner URL ships in the binary.

/// Builds the GCD rescue URL for a given install. Returns `""`
/// when the base or the dev key cannot be resolved so callers
/// treat the rescue as unavailable and keep whatever the AF SDK
/// already delivered.
String unsealGcdCallUrl(String bundleId, String deviceId) {
  final String base = unsealGcdBase();
  if (base.isEmpty) return '';
  final String key = unsealAttributionKey();
  if (key.isEmpty) return '';
  return '$base$bundleId?devkey=$key&device_id=$deviceId';
}

