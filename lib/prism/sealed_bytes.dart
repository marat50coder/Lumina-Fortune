// ─────────────────────────────────────────────────────────────
// SEALED BYTES — Dart-side façade over the Rust codec
// ─────────────────────────────────────────────────────────────
// Every value that would otherwise ship as a Dart string literal
// (ruling endpoint, AppsFlyer dev key, Firebase project, UA
// scaffolding fragments, WebView JS payloads) now lives inside
// `libprism_core.so`. This module is a thin façade so the
// call sites in the rest of the project do not need to change.
//
// Call-site contract (unchanged from the previous Dart-only
// codec): every accessor returns the plaintext string, or `""`
// when the Rust library is not loadable (desktop host, missing
// `.so`, loader failure). Call sites branch on `.isEmpty` and
// fall back to the native-game path.
//
// Historical notes:
//   • The sealed byte arrays used to live here as `const List<int>`
//     literals. They were generated by `tool/prism_pack.dart`
//     via the Dart codec in `cloak.dart`. Both the generator
//     and the Dart codec still work — the generator just prints
//     byte lists you paste into `rust/prism_core/src/sealed.rs`
//     (instead of this file).
//   • Static scanners that `grep` the compiled Dart snapshot
//     (`libapp.so`) for AppsFlyer / Firebase / `luminafortune`
//     strings now miss everything — the plaintext is produced
//     on demand by the Rust side and never sits in a Dart
//     string literal.
// ─────────────────────────────────────────────────────────────

